// Writes src/data/dimensions.ts: the pixel size of every photograph, so layouts can reserve the exact
// proportions (no cropping, no layout shift). Runs before dev and build.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const root = "public/images";
const out = {};

function size(buf) {
  let i = 2;
  while (i < buf.length) {
    if (buf[i] !== 0xff) { i++; continue; }
    const m = buf[i + 1];
    if (m >= 0xc0 && m <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(m)) return [buf.readUInt16BE(i + 7), buf.readUInt16BE(i + 5)];
    i += 2 + buf.readUInt16BE(i + 2);
  }
  return null;
}

(function walk(dir) {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) walk(p);
    else if (/\.jpe?g$/i.test(f)) {
      const d = size(readFileSync(p));
      if (d) out["/psgallery/images/" + relative(root, p)] = d;
    }
  }
})(root);

const body = Object.entries(out).sort().map(([k, v]) => `  "${k}": [${v[0]}, ${v[1]}],`).join("\n");
writeFileSync("src/data/dimensions.ts", `// Generated by scripts/dims.mjs. Do not edit.\nexport const DIMS: Record<string, [number, number]> = {\n${body}\n};\n`);
